-- =====================================================
-- USUÁRIOS
-- =====================================================

CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    PASSWORD VARCHAR2(255) NOT NULL,
    CREATED_AT DATE DEFAULT CURRENT_DATE,
    STATUS VARCHAR2(20) DEFAULT 'Active',

    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL)
);


-- =====================================================
-- PROPRIEDADES
-- =====================================================

CREATE TABLE PROPRIEDADE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    AREA_TOTAL NUMBER(10,2) NOT NULL,
    USER_ID NUMBER NOT NULL,

    CONSTRAINT PK_PROPRIEDADE PRIMARY KEY (ID),
    CONSTRAINT FK_PROPRIEDADE_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(ID),
    CONSTRAINT CK_PROPRIEDADE_AREA
        CHECK (AREA_TOTAL > 0)
);


-- =====================================================
-- TALHÕES
-- =====================================================

CREATE TABLE TALHAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    AREA NUMBER(10,2) NOT NULL,
    PROPRIEDADE_ID NUMBER NOT NULL,
    DESCRICAO VARCHAR2(500),

    CONSTRAINT PK_TALHAO PRIMARY KEY (ID),
    CONSTRAINT FK_TALHAO_PROPRIEDADE
        FOREIGN KEY (PROPRIEDADE_ID)
        REFERENCES PROPRIEDADE(ID),
    CONSTRAINT CK_TALHAO_AREA
        CHECK (AREA > 0)
);


-- =====================================================
-- CULTURAS
-- =====================================================

CREATE TABLE CULTURA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    DESCRICAO VARCHAR2(500),

    CONSTRAINT PK_CULTURA PRIMARY KEY (ID),
    CONSTRAINT UK_CULTURA_NOME UNIQUE (NOME)
);


-- =====================================================
-- PLANTIOS
-- =====================================================

CREATE TABLE PLANTIO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TALHAO_ID NUMBER NOT NULL,
    CULTURA_ID NUMBER NOT NULL,
    DATA_PLANTIO DATE NOT NULL,
    DATA_PREVISTA_COLHEITA DATE,
    PRODUTIVIDADE_ESTIMADA NUMBER(10,2),
    CUSTO_PRODUCAO NUMBER(12,2),
    STATUS VARCHAR2(30) DEFAULT 'Em andamento',
    OBSERVACOES VARCHAR2(500),

    CONSTRAINT PK_PLANTIO PRIMARY KEY (ID),

    CONSTRAINT FK_PLANTIO_TALHAO
        FOREIGN KEY (TALHAO_ID)
        REFERENCES TALHAO(ID),

    CONSTRAINT FK_PLANTIO_CULTURA
        FOREIGN KEY (CULTURA_ID)
        REFERENCES CULTURA(ID),

    CONSTRAINT CK_PLANTIO_CUSTO
        CHECK (CUSTO_PRODUCAO >= 0)
);


-- =====================================================
-- COLHEITAS
-- =====================================================

CREATE TABLE COLHEITA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PLANTIO_ID NUMBER NOT NULL,
    DATA_COLHEITA DATE NOT NULL,
    PRODUCAO_TOTAL NUMBER(12,2) NOT NULL,
    OBSERVACOES VARCHAR2(500),

    CONSTRAINT PK_COLHEITA PRIMARY KEY (ID),

    CONSTRAINT FK_COLHEITA_PLANTIO
        FOREIGN KEY (PLANTIO_ID)
        REFERENCES PLANTIO(ID),

    CONSTRAINT CK_COLHEITA_PRODUCAO
        CHECK (PRODUCAO_TOTAL >= 0)
);


-- =====================================================
-- INSUMOS
-- =====================================================

CREATE TABLE INSUMO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    TIPO VARCHAR2(50),
    UNIDADE_MEDIDA VARCHAR2(20) NOT NULL,
    ESTOQUE NUMBER(12,2) DEFAULT 0,

    CONSTRAINT PK_INSUMO PRIMARY KEY (ID),
    CONSTRAINT CK_INSUMO_ESTOQUE
        CHECK (ESTOQUE >= 0)
);


-- =====================================================
-- APLICAÇÃO DE INSUMOS
-- =====================================================

CREATE TABLE APLICACAO_INSUMO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TALHAO_ID NUMBER NOT NULL,
    INSUMO_ID NUMBER NOT NULL,
    DATA_APLICACAO DATE NOT NULL,
    QUANTIDADE NUMBER(12,2) NOT NULL,
    OBSERVACOES VARCHAR2(500),

    CONSTRAINT PK_APLICACAO_INSUMO PRIMARY KEY (ID),

    CONSTRAINT FK_APLICACAO_TALHAO
        FOREIGN KEY (TALHAO_ID)
        REFERENCES TALHAO(ID),

    CONSTRAINT FK_APLICACAO_INSUMO
        FOREIGN KEY (INSUMO_ID)
        REFERENCES INSUMO(ID),

    CONSTRAINT CK_APLICACAO_QUANTIDADE
        CHECK (QUANTIDADE > 0)
);
