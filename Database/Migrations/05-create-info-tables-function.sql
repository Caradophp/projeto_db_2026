CREATE OR REPLACE FUNCTION GET_TABLE_COUNTS
RETURN TABLE_COUNT_TAB
IS
    V_RESULT TABLE_COUNT_TAB := TABLE_COUNT_TAB();
    V_COUNT  NUMBER;
BEGIN
    FOR T IN (
        SELECT TABLE_NAME
        FROM USER_TABLES
        WHERE TABLE_NAME IN (
			'COLHEITA',
			'CULTURA',
			'CODES_SENT',
			'INSUMO',
			'MIGRATIONS',
			'APLICACAO_INSUMO',
			'TALHAO',
			'USERS',
			'PLANTIO',
			'PROPRIEDADE'
        )
        ORDER BY TABLE_NAME
    )
    LOOP
        EXECUTE IMMEDIATE
            'SELECT COUNT(*) FROM "' ||
            REPLACE(T.TABLE_NAME, '"', '""') || '"'
        INTO V_COUNT;

        V_RESULT.EXTEND;

        V_RESULT(V_RESULT.LAST) :=
            TABLE_COUNT_OBJ(T.TABLE_NAME, V_COUNT);
    END LOOP;

    RETURN V_RESULT;
END;

